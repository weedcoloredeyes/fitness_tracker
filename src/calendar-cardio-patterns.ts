export function cardioPatternForDate(date: string): string {
  let hash = 2166136261;
  for (let index = 0; index < date.length; index++) {
    hash = Math.imul(hash ^ date.charCodeAt(index), 16777619);
  }
  // Mix adjacent dates so their variants do not form a predictable sequence.
  hash = Math.imul(hash ^ (hash >>> 16), 0x7feb352d);
  hash = Math.imul(hash ^ (hash >>> 15), 0x846ca68b);
  hash ^= hash >>> 16;
  return CARDIO_PATTERNS[(hash >>> 0) % CARDIO_PATTERNS.length]!;
}
